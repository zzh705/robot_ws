# ============================================================
# 1. 提取图书搜索关键词
# ============================================================

def extract_keyword(question):
    """
    从用户自然语言中提取图书搜索关键词。

    示例：

    Python在哪里
    -> Python

    Python的书在哪
    -> Python

    我想找Python
    -> Python

    帮我找一本Python的书
    -> Python
    """

    keyword = question.strip()

    remove_words = [
        # 地点 / 查询表达
        "在哪里",
        "在哪儿",
        "在哪",
        "什么位置",
        "位置",
        "怎么找",
        "怎么去",

        # 图书相关表达
        "的书",
        "书籍",
        "图书",
        "这本书",
        "这本",

        # 请求表达
        "帮我找一本",
        "帮我找",
        "帮我查询",
        "帮我查一下",
        "帮我查",
        "我想找一本",
        "我想找",
        "我想查询",
        "我想查一下",
        "我想查",
        "请帮我找",
        "请帮我查询",
        "请帮我查",

        # 数量 / 泛化表达
        "一本",
        "一套",
    ]

    for word in remove_words:
        keyword = keyword.replace(word, "")

    return keyword.strip()


# ============================================================
# 2. 判断用户意图
# ============================================================

def detect_intent(text):
    """
    判断用户问题属于哪一种意图。

    返回：

    search  -> 查询/寻找图书
    borrow  -> 借书
    return  -> 还书
    ai      -> 普通 AI 问题
    """

    text = text.strip()

    # --------------------------------------------------------
    # 借书
    # --------------------------------------------------------

    borrow_words = [ "借书", "借阅", "我要借", "想借", "借一本", "借这本", "帮我借", ]

    for word in borrow_words:
        if word in text:
            return "borrow"

    # --------------------------------------------------------
    # 还书
    # --------------------------------------------------------

    return_words = [ "还书", "归还", "我要还", "想还", "还一本", "还这本", "帮我还", ]

    for word in return_words:
        if word in text:
            return "return"

    # --------------------------------------------------------
    # 查询 / 寻找图书
    # --------------------------------------------------------

    search_words = [ "找书", "找一本", "找一套", "我想找", "帮我找", "请帮我找", "寻找", "查找", "查询图书", "查图书", "查询书", "查书", "有没有", "有这本书吗", "有这本书", "在哪里", "在哪儿", "在哪", "什么位置", "位置", "怎么找", "怎么去", "书架", "馆藏", "库存", ]

    for word in search_words:
        if word in text:
            return "search"

    # --------------------------------------------------------
    # 其他问题交给 AI
    # --------------------------------------------------------

    return "ai"


# ============================================================
# 3. Library AI 总入口
# ============================================================

def book_chat(text):
    """
    Library AI 总入口。

    用户的问题从这里进入。

    当前支持：

    1. 查询图书
       -> extract_keyword()
       -> search_books()

    2. 借书
       -> 暂时返回提示
       -> 后续接入 borrow_book()

    3. 还书
       -> 暂时返回提示
       -> 后续接入 return_book()

    4. 普通问题
       -> ask_ai()
    """

    text = text.strip()

    # --------------------------------------------------------
    # 空消息
    # --------------------------------------------------------

    if not text:
        return "请输入你的问题。"

    # --------------------------------------------------------
    # 判断意图
    # --------------------------------------------------------

    intent = detect_intent(text)

    print(f"用户问题：{text}")
    print(f"识别意图：{intent}")

    # ========================================================
    # 查询图书
    # ========================================================

    if intent == "search":

        keyword = extract_keyword(text)

        print(f"提取关键词：{keyword}")

        if not keyword:
            return "请告诉我你想查询哪本书。"

        return search_books(keyword)

    # ========================================================
    # 借书
    # ========================================================

    elif intent == "borrow":

        # 暂时不执行数据库修改
        # 后续这里接：
        #
        # return borrow_book(...)

        return "我可以帮你办理借书。借书功能正在接入中。"

    # ========================================================
    # 还书
    # ========================================================

    elif intent == "return":

        # 暂时不执行数据库修改
        # 后续这里接：
        #
        # return return_book(...)

        return "我可以帮你办理还书。还书功能正在接入中。"

    # ========================================================
    # 普通 AI 对话
    # ========================================================

    else:

        return ask_ai(text)

